#!/usr/bin/env python3
"""
Heartbeat compression for CEO and CTO persistent agents.
Hourly cron: reads latest session transcripts, summarizes last 10 messages,
writes compressed state to heartbeat.md.
"""

import json
import os
import sys
from datetime import datetime
from pathlib import Path

# Workspace paths
CEO_WORKSPACE = Path("/home/ubuntu/.openclaw/workspace-ceo")
CTO_WORKSPACE = Path("/home/ubuntu/.openclaw/workspace-cto")

# Session store paths
CEO_SESSIONS = Path("/home/ubuntu/.openclaw/agents/ceo/sessions/sessions.json")
CTO_SESSIONS = Path("/home/ubuntu/.openclaw/agents/cto/sessions/sessions.json")

def get_latest_session_transcript(sessions_path):
    """Return path to transcript of most recently updated active session."""
    try:
        with open(sessions_path, 'r') as f:
            sessions = json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return None
    
    # sessions.json is an array of session objects
    if not isinstance(sessions, list):
        return None
    
    # Find active (non-ended) sessions, sort by updatedAt descending
    active = [s for s in sessions if s.get('status') in ('running', None)]
    if not active:
        return None
    
    latest = max(active, key=lambda s: s.get('updatedAt', 0))
    transcript_path = latest.get('transcriptPath')
    if not transcript_path:
        return None
    
    return Path(transcript_path)

def read_last_messages(transcript_path, count=10):
    """Read last N messages from transcript JSONL file."""
    if not transcript_path or not transcript_path.exists():
        return []
    
    messages = []
    try:
        with open(transcript_path, 'r') as f:
            lines = f.readlines()
        # Read last lines (up to count*2 because each message may be multiple lines)
        for line in reversed(lines[-count*2:]):
            try:
                entry = json.loads(line.strip())
                if entry.get('type') == 'message':
                    msg = entry.get('message', {})
                    role = msg.get('role')
                    content = msg.get('content', [])
                    # Extract text from content array
                    text = ''
                    for item in content:
                        if isinstance(item, dict) and item.get('type') == 'text':
                            text = item.get('text', '')
                            break
                    if role and text:
                        messages.append({'role': role, 'text': text})
            except json.JSONDecodeError:
                continue
            if len(messages) >= count:
                break
    except Exception as e:
        print(f"Error reading transcript {transcript_path}: {e}", file=sys.stderr)
    
    return list(reversed(messages))  # Restore chronological order

def summarize_messages(messages):
    """Create a concise summary of recent conversation."""
    if not messages:
        return "No recent activity."
    
    user_msgs = [m['text'] for m in messages if m['role'] == 'user']
    assistant_msgs = [m['text'] for m in messages if m['role'] == 'assistant']
    
    summary = []
    summary.append(f"Last {len(messages)} messages ({len(user_msgs)} user, {len(assistant_msgs)} assistant):")
    
    if user_msgs:
        # Extract key topics from last few user messages
        recent_user = user_msgs[-3:] if len(user_msgs) >= 3 else user_msgs
        topics = []
        for msg in recent_user:
            # Simple extraction: first 50 chars
            if len(msg) > 50:
                topics.append(msg[:50].replace('\n', ' ') + "...")
            else:
                topics.append(msg.replace('\n', ' '))
        summary.append(f"Recent user topics: {' | '.join(topics)}")
    
    # Note any tasks completed or pending
    if any('task' in msg.lower() or 'completed' in msg.lower() for msg in assistant_msgs):
        summary.append("Status: tasks in progress or recently completed.")
    
    return '\n'.join(summary)

def write_heartbeat(workspace_path, summary):
    """Write compressed summary to heartbeat.md."""
    heartbeat_path = workspace_path / "HEARTBEAT.md"
    timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    
    content = f"""# Heartbeat Compression — {timestamp}

## Context Summary
{summary}

## Next Actions
- Continue current tasks
- Maintain context discipline
- Monitor session hygiene

---
*Auto‑generated by heartbeat_compress.py*
"""
    
    try:
        with open(heartbeat_path, 'w') as f:
            f.write(content)
        print(f"Updated {heartbeat_path}")
    except Exception as e:
        print(f"Error writing heartbeat: {e}", file=sys.stderr)

def main():
    """Compress heartbeat for CEO and CTO."""
    # CEO
    ceo_transcript = get_latest_session_transcript(CEO_SESSIONS)
    ceo_messages = read_last_messages(ceo_transcript, 10)
    ceo_summary = summarize_messages(ceo_messages)
    write_heartbeat(CEO_WORKSPACE, ceo_summary)
    
    # CTO
    cto_transcript = get_latest_session_transcript(CTO_SESSIONS)
    cto_messages = read_last_messages(cto_transcript, 10)
    cto_summary = summarize_messages(cto_messages)
    write_heartbeat(CTO_WORKSPACE, cto_summary)
    
    print("Heartbeat compression completed.")

if __name__ == '__main__':
    main()